export const messages: Record<Language, Messages> = { en, fi };

export function statusText(language: Language, status: TaskStatus): string {
  const text = messages[language];
  switch (status) {
    case "done":
      return text.statusDone;
    case "overdue":
      return text.overdue;
    case "upcoming":
      return text.upcoming;
    case "active":
      return text.active;
    case "ended":
      return text.ended;
  }
}

export function ideaCount(language: Language, count: number): string {
  if (language === "fi") return count === 1 ? "1 idea" : `${count} ideaa`;
  return count === 1 ? "1 idea" : `${count} ideas`;
}
